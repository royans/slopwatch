"""
Established packages, and registry-enforced proof that a package belongs to the same owner.

The bundled lists (signatures/established_{npm,pypi}.txt, regenerated by
scripts/refresh_established_packages.py) hold the ~17k npm and 15k PyPI packages that
matter most. Three kinds of identity evidence come from them, strongest first:

  established  the package itself is on the list. It is not a squat of anything.
  scope        npm only: its scope (`@playwright/…`) already publishes an established
               package. Only the scope's owner can publish under it, so this is the
               same owner — `@playwright/browser-firefox` is Microsoft's, not a squat.
  publisher    npm only: it shares a publishing account (`maintainers` / `_npmUser`)
               with an established package whose name it extends (`playwright-firefox`
               and `playwright`). npm accounts are authenticated, unlike manifest
               `author` fields or PyPI author emails, so this cannot be claimed.

None of these clears malware: a compromised maintainer account is how established
packages get hijacked. Callers keep treating confirmed-dangerous code as a takeover.
"""

from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, FrozenSet, Iterable, List, Optional, Tuple

_SIGNATURES = Path(__file__).resolve().parent.parent / "signatures"
_MAX_SIBLING_LOOKUPS = 3


def _eco(ecosystem: Any) -> str:
    return str(getattr(ecosystem, "value", ecosystem)).lower()


def _norm(eco: str, name: str) -> str:
    name = name.strip().lower()
    return re.sub(r"[-_.]+", "-", name) if eco == "pypi" else name


@lru_cache(maxsize=4)
def _ranked(eco: str) -> Dict[str, int]:
    path = _SIGNATURES / f"established_{eco}.txt"
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return {}
    names = [ln.strip() for ln in lines if ln.strip() and not ln.startswith("#")]
    return {_norm(eco, n): i for i, n in enumerate(names)}


def is_established(ecosystem: Any, name: str) -> bool:
    eco = _eco(ecosystem)
    return _norm(eco, name) in _ranked(eco)


def npm_scope(name: str) -> Optional[str]:
    name = name.strip().lower()
    return name.split("/", 1)[0] if name.startswith("@") and "/" in name else None


@lru_cache(maxsize=1)
def established_npm_scopes() -> FrozenSet[str]:
    return frozenset(s for s in (npm_scope(n) for n in _ranked("npm")) if s)


def established_scope(ecosystem: Any, name: str) -> Optional[str]:
    """The npm scope of ``name`` if that scope already publishes an established package."""
    if _eco(ecosystem) != "npm":
        return None
    scope = npm_scope(name)
    return scope if scope and scope in established_npm_scopes() else None


def established_siblings(ecosystem: Any, name: str, limit: int = _MAX_SIBLING_LOOKUPS) -> List[str]:
    """Established packages ``name`` extends: same leading token (`playwright-firefox` -> `playwright`)."""
    eco = _eco(ecosystem)
    norm = _norm(eco, name)
    bare = norm.split("/", 1)[1] if norm.startswith("@") and "/" in norm else norm
    token = re.split(r"[-_.]", bare, maxsplit=1)[0]
    if len(token) < 4:
        return []
    ranked = _ranked(eco)
    hits = [
        n for n in ranked
        if n != norm and (n == token or n.startswith(token + "-") or n.endswith("/" + token))
    ]
    hits.sort(key=lambda n: (n != token, ranked[n]))
    return hits[:limit]


def publisher_accounts(maintainers: Iterable[str]) -> FrozenSet[str]:
    """``["alice <a@x.com>", "bob"]`` -> ``{"alice", "bob"}`` (npm account names)."""
    out = set()
    for m in maintainers or ():
        acct = str(m).split("<", 1)[0].strip().lower()
        if acct:
            out.add(acct)
    return frozenset(out)


async def established_identity(
    adapter: Any, ecosystem: Any, name: str, meta: Any = None
) -> Optional[Tuple[str, str]]:
    """Registry-enforced evidence that ``name`` belongs to an established owner.

    Returns ``(kind, ref)`` — ``("established", name)``, ``("scope", "@playwright")`` or
    ``("publisher", "playwright")`` — or None. The publisher check costs up to
    three cached metadata lookups and only runs for npm.
    """
    if is_established(ecosystem, name):
        return "established", name
    scope = established_scope(ecosystem, name)
    if scope:
        return "scope", scope
    if _eco(ecosystem) != "npm" or adapter is None:
        return None
    accounts = publisher_accounts(getattr(meta, "maintainers", None) or [])
    if not accounts:
        return None
    for sibling in established_siblings(ecosystem, name):
        try:
            sib_meta = await adapter.inspect_package_metadata(sibling)
        except Exception:
            continue
        if sib_meta and accounts & publisher_accounts(getattr(sib_meta, "maintainers", None) or []):
            return "publisher", sibling
    return None
